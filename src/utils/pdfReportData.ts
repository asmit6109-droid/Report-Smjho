function combineBilingualText(
  lang: SupportedLanguage,
  bilingual: boolean,
  enText: string,
  translatedText?: string
): string {
  const cleanEn = (enText || '').trim();
  const cleanTr = (translatedText || '').trim();
  if (lang === 'en') return cleanEn;
  if (!bilingual) return cleanTr || cleanEn;
  if (!cleanTr || cleanTr === cleanEn) return cleanEn;
  if (!cleanEn) return cleanTr;
  return `${cleanTr} / ${cleanEn}`;
}

function combineBilingualList(
  lang: SupportedLanguage,
  bilingual: boolean,
  enList: string[] = [],
  trList: string[] = []
): string[] {
  if (lang === 'en') return enList;
  if (!bilingual) return trList.length > 0 ? trList : enList;
  const maxLen = Math.max(enList.length, trList.length);
  const out: string[] = [];
  for (let i = 0; i < maxLen; i++) {
    const line = combineBilingualText(lang, true, enList[i] || '', trList[i] || '');
    if (line) out.push(line);
  }
  return out;
}

function formatDateNice(raw?: string): string {
  if (!raw) return new Date().toLocaleDateString('en-IN');
  const d = new Date(raw);
  if (Number.isNaN(d.getTime())) return raw;
  return d.toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

function getStatusBadgeInfo(
  status: Finding['status'],
  lang: SupportedLanguage,
  bilingual: boolean
): { text: string; shape: 'check' | 'down' | 'up' | 'alert' } {
  const tEn = translations.en;
  const tLang = translations[lang];
  if (status === 'critical') {
    const trWord = lang === 'hi' ? 'गंभीर' : lang === 'or' ? 'ଅତ୍ୟଧିକ' : 'Critical';
    return {
      text: bilingual && lang !== 'en' ? `[!!] ${trWord} / Critical` : `[!!] ${trWord}`,
      shape: 'alert',
    };
  }
  if (status === 'high') {
    return {
      text:
        bilingual && lang !== 'en'
          ? `[^] ${tLang.valueHigh} / ${tEn.valueHigh}`
          : `[^] ${tLang.valueHigh}`,
      shape: 'up',
    };
  }
  if (status === 'low') {
    return {
      text:
        bilingual && lang !== 'en'
          ? `[v] ${tLang.valueLow} / ${tEn.valueLow}`
          : `[v] ${tLang.valueLow}`,
      shape: 'down',
    };
  }
  return {
    text:
      bilingual && lang !== 'en'
        ? `[OK] ${tLang.valueNormal} / ${tEn.valueNormal}`
        : `[OK] ${tLang.valueNormal}`,
    shape: 'check',
  };
}

function getAccessTagLabel(
  level: MedicineAccessLevel,
  lang: SupportedLanguage,
  bilingual: boolean
): string {
  const mtEn = medicineTranslations.en;
  const mtLang = medicineTranslations[lang];
  if (level === 'otc') {
    return combineBilingualText(lang, bilingual, mtEn.accessOtc, mtLang.accessOtc);
  }
  if (level === 'prescription_only') {
    return combineBilingualText(lang, bilingual, mtEn.accessPrescriptionOnly, mtLang.accessPrescriptionOnly);
  }
  return combineBilingualText(lang, bilingual, mtEn.accessAskDoctor, mtLang.accessAskDoctor);
}

export function getLinkedMedicinesCountForReport(
  report: ReportAnalysis,
  combinedData?: CombinedReportData | null
): { linkedCount: number; totalSavedCount: number } {
  const targetIds = new Set<string>([
    report.id,
    ...(combinedData?.scans.map((s) => s.report.id) || []),
  ]);
  const storedMeds = getStoredMedicines();
  const storedRx = getStoredPrescriptions();

  const seenIds = new Set<string>();
  for (const m of storedMeds) {
    if (m.linked_report_id && targetIds.has(m.linked_report_id)) {
      seenIds.add(m.id);
    }
  }
  for (const rx of storedRx) {
    if (rx.linked_report_id && targetIds.has(rx.linked_report_id)) {
      for (const m of rx.medicines || []) {
        seenIds.add(m.id);
      }
    }
  }

  return {
    linkedCount: seenIds.size,
    totalSavedCount: storedMeds.length,
  };
}

export function buildFullPdfPayload(
  baseReport: ReportAnalysis,
  combinedData: CombinedReportData | null,
  options: PdfExportOptions
): PdfReportPayload {
  const { language, includeEnglishBilingual, includePatientIdentity, includeAllSavedMedicines } =
    options;
  const activeReport = combinedData ? combinedData.merged : baseReport;
  const labels = getPdfUiLabels(language, includeEnglishBilingual);
  const tEn = translations.en;
  const tLang = translations[language];

  // 1. Header
  const reportTitle = combineBilingualText(
    language,
    includeEnglishBilingual,
    activeReport.report_type,
    activeReport.translations?.[language]?.report_type
  );

  const reportDate = formatDateNice(activeReport.report_date || activeReport.created_at);
  const generatedAt = new Date().toLocaleString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  let patientLine: string | null = null;
  if (includePatientIdentity) {
    const profile = getStoredProfile();
    const pName = activeReport.patient_name;
    const pAge = activeReport.patient_age ?? profile.age;
    const pGender = activeReport.patient_gender ?? profile.gender;
    const parts: string[] = [];
    if (pName) parts.push(pName);
    if (pAge) parts.push(`${pAge} yrs`);
    if (pGender) {
      parts.push(pGender.charAt(0).toUpperCase() + pGender.slice(1));
    }
    patientLine = parts.length > 0 ? parts.join(' • ') : 'Patient profile included';
  }

  // 2. Overall Status
  const statusWord: 'NORMAL' | 'BE CAREFUL' | 'DANGER' =
    activeReport.overall_severity === 'green'
      ? 'NORMAL'
      : activeReport.overall_severity === 'yellow'
      ? 'BE CAREFUL'
      : 'DANGER';

  const statusTranslated =
    activeReport.overall_severity === 'green'
      ? tLang.statusGreen
      : activeReport.overall_severity === 'yellow'
      ? tLang.statusYellow
      : tLang.statusRed;

  const statusDisplay =
    language === 'en'
      ? statusWord
      : includeEnglishBilingual
      ? `${statusWord} (${statusTranslated})`
      : `${statusTranslated} (${statusWord})`;

  const severityReason = combineBilingualText(
    language,
    includeEnglishBilingual,
    activeReport.severity_reason,
    activeReport.translations?.[language]?.severity_reason
  );

  const emergencyBannerText = combineBilingualText(
    language,
    includeEnglishBilingual,
    `${tEn.emergencyBanner} ${tEn.emergencySub} (Emergency: 108 / 104)`,
    `${tLang.emergencyBanner} ${tLang.emergencySub}`
  );

  // 3. Body Map
  const bodySummary = buildBodyRegionSummaries(
    activeReport.findings || [],
    activeReport.report_type,
    language
  );
  const regionsList = bodySummary.orderedRegionIds.map((rId) => bodySummary.regions[rId]);
  const legendRows = regionsList.map((r) => {
    const kindLabel = r.mappingKind === 'affected_injury' ? labels.affectedArea : labels.relatedArea;
    const statusText =
      r.severity === 'danger'
        ? 'DANGER'
        : r.severity === 'caution'
        ? 'BE CAREFUL'
        : 'NORMAL';
    return {
      regionId: r.regionId,
      areaLabel: r.areaLabel,
      kindLabel,
      severity: r.severity,
      statusText,
    };
  });

  // 4. All Findings grouped by category (INCLUDING normal results!)
  const categoryMap = new Map<string, PdfFindingRow[]>();
  const categoryOrder: string[] = [];

  for (const f of activeReport.findings || []) {
    const mapped = resolveFindingBodyMapping(f, activeReport.report_type, language);
    const mappedEn =
      includeEnglishBilingual && language !== 'en'
        ? resolveFindingBodyMapping(f, activeReport.report_type, 'en')
        : null;

    const categoryName = mapped
      ? mappedEn && mappedEn.areaLabel !== mapped.areaLabel
        ? `${mapped.areaLabel} (${mappedEn.areaLabel})`
        : mapped.areaLabel
      : labels.otherTests;

    const areaText = mapped
      ? `${mapped.areaLabel} (${
          mapped.mappingKind === 'affected_injury' ? labels.affectedArea : labels.relatedArea
        })`
      : labels.otherTests;

    const testName = combineBilingualText(
      language,
      includeEnglishBilingual,
      f.name,
      f.translations?.[language]?.name
    );

    const badge = getStatusBadgeInfo(f.status, language, includeEnglishBilingual);
    const rangeSourceText =
      f.range_source === 'lab' ? labels.labRange : labels.generalRange;

    const row: PdfFindingRow = {
      id: f.id,
      testName,
      value: f.value || '—',
      unit: f.unit || '—',
      normalRange: f.reference_range || '—',
      status: f.status,
      statusText: badge.text,
      statusShape: badge.shape,
      rangeSourceText,
      relatedAreaText: areaText,
      scanLabel: f.source_label ? `${f.source_label}${f.source_date ? ` (${f.source_date})` : ''}` : '',
      category: categoryName,
    };

    if (!categoryMap.has(categoryName)) {
      categoryMap.set(categoryName, []);
      categoryOrder.push(categoryName);
    }
    categoryMap.get(categoryName)!.push(row);
  }

  const findingCategories: PdfFindingCategoryGroup[] = categoryOrder.map((cat) => ({
    categoryName: cat,
    rows: categoryMap.get(cat)!,
  }));

  // 5. Abnormal Explanations
  const abnormalExplanations: PdfAbnormalExplanation[] = (activeReport.findings || [])
    .filter((f) => f.status !== 'normal')
    .map((f) => {
      const badge = getStatusBadgeInfo(f.status, language, includeEnglishBilingual);
      return {
        id: f.id,
        testName: combineBilingualText(
          language,
          includeEnglishBilingual,
          f.name,
          f.translations?.[language]?.name
        ),
        valueText: `${f.value}${f.unit ? ` ${f.unit}` : ''}`,
        status: f.status,
        statusText: badge.text,
        explanation: combineBilingualText(
          language,
          includeEnglishBilingual,
          f.short_explanation,
          f.translations?.[language]?.short_explanation
        ),
        scanLabel: f.source_label,
      };
    });

  // 6. Symptoms to watch
  const symptoms = combineBilingualList(
    language,
    includeEnglishBilingual,
    activeReport.symptoms_to_watch || [],
    activeReport.translations?.[language]?.symptoms_to_watch || []
  );

  // 7. How Urgent
  const urgencyLabel =
    activeReport.urgency === 'today'
      ? combineBilingualText(language, includeEnglishBilingual, tEn.urgencyToday, tLang.urgencyToday)
      : activeReport.urgency === 'soon'
      ? combineBilingualText(language, includeEnglishBilingual, tEn.urgencySoon, tLang.urgencySoon)
      : combineBilingualText(language, includeEnglishBilingual, tEn.urgencyRoutine, tLang.urgencyRoutine);

  // 8. Safe steps
  const safeSteps = combineBilingualList(
    language,
    includeEnglishBilingual,
    activeReport.safe_steps || [],
    activeReport.translations?.[language]?.safe_steps || []
  );

  // 9. Doctor questions
  const doctorQuestions = combineBilingualList(
    language,
    includeEnglishBilingual,
    activeReport.doctor_questions || [],
    activeReport.translations?.[language]?.doctor_questions || []
  );

  // 10. Linked & Saved Medicines
  const targetReportIds = new Set<string>([
    baseReport.id,
    ...(combinedData?.scans.map((s) => s.report.id) || []),
  ]);
  const storedMeds = getStoredMedicines();
  const storedRx = getStoredPrescriptions();
  const sameSaltPairs = detectSameSaltPairs(storedMeds);

  const collectedMedsMap = new Map<string, MedicineAnalysis>();
  for (const m of storedMeds) {
    if ((m.linked_report_id && targetReportIds.has(m.linked_report_id)) || includeAllSavedMedicines) {
      collectedMedsMap.set(m.id, m);
    }
  }
  for (const rx of storedRx) {
    if (rx.linked_report_id && targetReportIds.has(rx.linked_report_id)) {
      for (const m of rx.medicines || []) {
        if (!collectedMedsMap.has(m.id)) {
          collectedMedsMap.set(m.id, {
            ...m,
            connection_summary: m.connection_summary || rx.why_this_prescription,
          });
        }
      }
    }
  }

  const medicines: PdfMedicineEntry[] = Array.from(collectedMedsMap.values()).map((med) => {
    const tr = language !== 'en' ? med.translations?.[language] : undefined;
    const warnings: string[] = [];

    if (med.medicine.is_expired) {
      warnings.push(
        language === 'hi'
          ? `दवा एक्सपायर हो चुकी है (${med.medicine.expiry || ''})`
          : language === 'or'
          ? `ଔଷଧର ମିଆଦ ଶେଷ ହୋଇଛି (${med.medicine.expiry || ''})`
          : `EXPIRED medicine (${med.medicine.expiry || 'check pack'})`
      );
    }
    if (med.allergy_condition_warning) {
      warnings.push(
        combineBilingualText(
          language,
          includeEnglishBilingual,
          med.allergy_condition_warning,
          tr?.allergy_condition_warning
        )
      );
    }
    for (const rf of med.risk_flags || []) {
      warnings.push(rf);
    }
    // Check same-salt duplicate warnings across user's saved medicines
    for (const pair of sameSaltPairs) {
      if (pair.medA.id === med.id || pair.medB.id === med.id) {
        const other = pair.medA.id === med.id ? pair.medB : pair.medA;
        warnings.push(
          `Same salt warning (${pair.sharedSalt}) also found in ${other.medicine.brand}`
        );
      }
    }

    const visualEn = resolveMedicineVisual(med, 'en');
    const visualLang = resolveMedicineVisual(med, language);
    const visualUsedForLine = combineBilingualText(
      language,
      includeEnglishBilingual,
      visualEn.fullUsedForLine,
      visualLang.fullUsedForLine
    );
    const visualRelatedNote = visualLang.relatedAreaNote
      ? combineBilingualText(
          language,
          includeEnglishBilingual,
          visualEn.relatedAreaNote || visualLang.relatedAreaNote,
          visualLang.relatedAreaNote
        )
      : null;

    return {
      id: med.id,
      brand: combineBilingualText(
        language,
        includeEnglishBilingual,
        med.medicine.brand,
        tr?.brand
      ),
      salt: combineBilingualText(
        language,
        includeEnglishBilingual,
        med.medicine.salt || 'Not listed',
        tr?.salt
      ),
      strength: med.medicine.strength || 'Not specified',
      whoCanGive: getAccessTagLabel(
        med.medicine.access_level,
        language,
        includeEnglishBilingual
      ),
      accessLevel: med.medicine.access_level,
      usedFor: combineBilingualText(
        language,
        includeEnglishBilingual,
        med.purpose,
        tr?.purpose
      ),
      commonSideEffects: combineBilingualList(
        language,
        includeEnglishBilingual,
        med.side_effects_common || [],
        tr?.side_effects_common || []
      ),
      seeDoctorSideEffects: combineBilingualList(
        language,
        includeEnglishBilingual,
        med.side_effects_see_doctor || [],
        tr?.side_effects_see_doctor || []
      ),
      warnings: Array.from(new Set(warnings)),
      whyGiven: med.connection_summary?.why_given || undefined,
      visual: visualLang,
      visualUsedForLine,
      visualRelatedNote,
      packThumbnail:
        med.pack_thumbnail && /^data:image\/(?:jpeg|jpg|png|webp);base64,/i.test(med.pack_thumbnail)
          ? med.pack_thumbnail
          : undefined,
    };
  });

  // 11. Combined Scans list
  const combinedScans: PdfCombinedScanItem[] = (combinedData?.scans || []).map((scan) => {
    const sev = scan.report.overall_severity;
    const statusLabel = sev === 'green' ? 'NORMAL' : sev === 'yellow' ? 'BE CAREFUL' : 'DANGER';
    return {
      scanLabel: scan.label,
      reportType: combineBilingualText(
        language,
        includeEnglishBilingual,
        scan.report.report_type,
        scan.report.translations?.[language]?.report_type
      ),
      dateLabel: scan.dateLabel || formatDateNice(scan.report.created_at),
      severity: sev,
      statusLabel,
      reason: combineBilingualText(
        language,
        includeEnglishBilingual,
        scan.report.severity_reason,
        scan.report.translations?.[language]?.severity_reason
      ),
    };
  });

  // 12. Trends (combine stored reports + current report / combined scans)
  const storedReports = getStoredReports();
  const reportPoolMap = new Map<string, ReportAnalysis>();
  for (const r of storedReports) reportPoolMap.set(r.id, r);
  reportPoolMap.set(baseReport.id, baseReport);
  for (const s of combinedData?.scans || []) {
    reportPoolMap.set(s.report.id, s.report);
  }
  const trends = calculateMarkerTrends(Array.from(reportPoolMap.values()));

  return {
    options,
    labels,
    header: {
      appName: 'ReportSamjho',
      reportTitle,
      reportDate,
      generatedAt,
      patientLine,
      isCombined: Boolean(combinedData && combinedData.scans.length > 0),
      groupName: combinedData?.groupName,
    },
    overallStatus: {
      severity: activeReport.overall_severity,
      statusWord,
      statusDisplay,
      reason: severityReason,
      hasEmergency: activeReport.overall_severity === 'red',
      emergencyBannerText,
    },
    bodyMap: {
      regions: regionsList,
      legendRows,
    },
    findingCategories,
    allFindingsCount: (activeReport.findings || []).length,
    abnormalExplanations,
    symptoms,
    urgency: {
      level: activeReport.urgency,
      label: urgencyLabel,
    },
    safeSteps,
    doctorQuestions,
    medicines,
    combinedScans,
    combinedMismatchWarning: combinedData?.mismatchWarning
      ? 'Note: Included scans appear to be from different people or dates. Please verify with your doctor.'
      : undefined,
    trends,
    footerText: labels.footerText,
  };
}
